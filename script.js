    // Neroa Screenshots (Landscape 16:9 Frame)
    const neroaNames = {
        '01': '01_slideshow.webp',
        '02': '02_filter.webp',
        '03': '03_everything_at_a_glance.webp',
        '04': '04_widgets.webp',
        '05': '05_video.webp',
        '06': '06_albums.webp',
        '07': '07_music.webp'
    };

    document.querySelectorAll('.carousel-slide[data-app="neroa"]').forEach(slide => {
        const slideNum = slide.dataset.slideNum;
        const img = slide.querySelector('img');
        if (slideNum && img && neroaNames[slideNum]) {
            const relPrefix = isSubFolder ? '' : 'neroa/';
            img.src = `${relPrefix}assets/screenshot/${neroaLangFolder}/${neroaNames[slideNum]}`;
        }
    });

