function getInitialLanguage() {
    const saved = localStorage.getItem('app_lang');
    if (saved && translations[saved]) return saved;
    const navLang = (navigator.language || navigator.userLanguage || '').toLowerCase();
    if (navLang.startsWith('ja')) return 'ja';
    if (navLang.startsWith('en')) return 'en';
    return 'ko';
}

let currentLang = getInitialLanguage();
let currentSlideIndex = 0;

// Realtime User Local Digital Clock
function updateRealtimeClock() {
    const clockEl = document.getElementById('realtime-clock-display');
    if (!clockEl) return;

    const now = new Date();
    const hours = String(now.getHours()).padStart(2, '0');
    const minutes = String(now.getMinutes()).padStart(2, '0');
    const seconds = String(now.getSeconds()).padStart(2, '0');

    // Detect User Timezone City Name
    let city = 'SEOUL';
    try {
        const timeZone = Intl.DateTimeFormat().resolvedOptions().timeZone || '';
        if (timeZone.includes('Tokyo')) city = 'TOKYO';
        else if (timeZone.includes('London')) city = 'LONDON';
        else if (timeZone.includes('New_York')) city = 'NEW YORK';
        else if (timeZone.includes('Paris')) city = 'PARIS';
        else if (timeZone.split('/')[1]) city = timeZone.split('/')[1].replace('_', ' ').toUpperCase();
    } catch (e) {}

    clockEl.textContent = `${city} ${hours}:${minutes}:${seconds}`;
}

function updateCarousel() {
    const track = document.getElementById('carousel-track');
    if (!track) return;
    const slides = track.querySelectorAll('.carousel-slide');
    if (slides.length === 0) return;

    if (currentSlideIndex >= slides.length) currentSlideIndex = 0;
    if (currentSlideIndex < 0) currentSlideIndex = slides.length - 1;

    track.style.transform = `translateX(-${currentSlideIndex * 100}%)`;

    document.querySelectorAll('.carousel-dot').forEach((dot, index) => {
        dot.classList.toggle('active', index === currentSlideIndex);
    });

    const activeSlide = slides[currentSlideIndex];
    const captionEl = document.getElementById('carousel-caption');
    if (activeSlide && captionEl) {
        const captionKey = activeSlide.dataset.i18nCaption;
        const dict = translations[currentLang];
        if (dict && dict[captionKey]) {
            captionEl.textContent = dict[captionKey];
        }
    }
}

function nextSlide() {
    const track = document.getElementById('carousel-track');
    if (!track) return;
    const slides = track.querySelectorAll('.carousel-slide');
    currentSlideIndex = (currentSlideIndex + 1) % slides.length;
    updateCarousel();
}

function prevSlide() {
    const track = document.getElementById('carousel-track');
    if (!track) return;
    const slides = track.querySelectorAll('.carousel-slide');
    currentSlideIndex = (currentSlideIndex - 1 + slides.length) % slides.length;
    updateCarousel();
}

function goToSlide(index) {
    currentSlideIndex = index;
    updateCarousel();
}

